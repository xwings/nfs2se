/* Browser platform layer for the translated NFS2SE game (NFS2SE.cpp).
 *
 * NFS2SE.cpp declares every import as extern "C" int32_t f(int32_t...), so
 * each definition here must return int32_t and take 32-bit arguments; pointer
 * parameters are fine because wasm32 pointers are i32. wasm-ld turns any
 * mismatch into a trapping stub, see the link check in the Makefile. */
#ifndef NFS2SE_PLATFORM_H
#define NFS2SE_PLATFORM_H

#include "web_layout.h"

#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>

#define GAME_TITLE "Need for Speed II SE"
#define MAX_PATH 260 /* size of the game's path buffers */

/* Every translated game function and callback has the signature void(Game *). */
typedef void (*GameFn)(void *game);

/* Glue defined at the end of NFS2SE.cpp. */
void nfs2seEntrypoint(void);
void sub_41B250(void *game, int32_t arg1, int32_t arg2);
void wrap_regparm2(void *game, GameFn func, int32_t arg0, int32_t arg1);
int32_t wrap_stdcall2_ret(void *game, GameFn func, int32_t arg0, int32_t arg1);
void wrap_stdcall4(void *game, GameFn func, int32_t arg0, int32_t arg1, int32_t arg2, int32_t arg3);

/* Game variables exported by NFS2SE.cpp as pointers into its data/bss. */
extern void *main_game_thread, *audio_game_thread;
extern void **dword_4DDA70, **dword_5637CC, **dword_5637D8;
extern void *dword_4DB1B0, *dword_5637A0, *dword_557540;
extern void *mousePositionX, *mousePositionY, *inControlAssignMode, *binaryGameVersion;

/* DirectInput vtable targets generated by NFS2SE.cpp (WrapFunctionNArg). */
void Release_wrap(void *game);
void CreateDevice_wrap(void *game);
void EnumDevices_wrap(void *game);
void QueryInterface_wrap(void *game);
void GetCapabilities_wrap(void *game);
void SetProperty_wrap(void *game);
void Acquire_wrap(void *game);
void Unacquire_wrap(void *game);
void GetDeviceState_wrap(void *game);
void GetDeviceData_wrap(void *game);
void SetDataFormat_wrap(void *game);
void SetEventNotification_wrap(void *game);
void SetCooperativeLevel_wrap(void *game);
void GetObjectInfo_wrap(void *game);
void CreateEffect_wrap(void *game);
void SendForceFeedbackCommand_wrap(void *game);
void Poll_wrap(void *game);
void SetParameters_wrap(void *game);
void Start_wrap(void *game);
void Stop_wrap(void *game);
void Download_wrap(void *game);
void Unload_wrap(void *game);

/* config.c: nfs2se.conf and path mapping (tested by tests/c/config_test.c). */
#define JOY_AXES 6 /* configurable axes per joystick */
#define JOY_DPAD_BUTTONS 4 /* right, left, down, up: the game's key order */

typedef struct
{
	bool keepAspectRatio;
	bool linearFiltering;
	bool joystickApplyDeadzone;
	bool joystickDisableAxesInMenu;
	int32_t joystickAxes[CTL_PAD_COUNT][JOY_AXES];     /* source axis of each game axis, or -1 */
	int32_t joystickAxisModes[CTL_PAD_COUNT][JOY_AXES]; /* 0 full, positive half, negative inverted half */
	int32_t joystickEscButton[CTL_PAD_COUNT];
	int32_t joystickResetButton[CTL_PAD_COUNT];
	int32_t joystickDPadButtons[CTL_PAD_COUNT][JOY_DPAD_BUTTONS];
} Config;

extern Config g_config;

void config_reset(void);
void config_parse(FILE *f);
void config_set_settings_dir(const char *dir); /* NULL keeps user data in the game directory */
char *config_convert_path(const char *gamePath, bool toLower); /* malloc'd, NULL when out of memory */
FILE *config_fopen(const char *gamePath, const char *mode);
const char *config_check_game_dirs(void); /* NULL when ok, else an error message */

/* fmt_x86.c */
int32_t fmt_x86_vsprintf(char *out, const char *fmt, const uint8_t *args);

/* kernel32.c */
int32_t SetEvent_wrap(void *event);

/* wrapper.c */
void wrapper_exit_procs(void); /* runs the WrapperAtExit procedures once */
_Noreturn void wrapper_fatal(const char *message); /* shows message, then exits */

/* user32.c */
int32_t user32_open_window(GameFn wndProc); /* returns the window handle */
bool user32_post_key(bool down, int32_t vk, int32_t scancode); /* false when the queue is full */
bool user32_window_alive(void);

/* web.c: browser integration. */
int32_t *web_ctl(void);
int32_t *web_audio(void); /* AUD_* header words, then frames */
uint8_t *web_gfx_slot(int index); /* GFX_SLOT_BYTES bytes */
void web_futex_wait(int32_t *addr, int32_t expected, uint32_t ms); /* while *addr == expected, up to ms */
void web_futex_wake(int32_t *addr);
int32_t web_message_box(const char *text, const char *caption, bool okCancel); /* DIALOG_OK or DIALOG_CANCEL */
const char *web_save_dir(void); /* persisted directory for settings and saves, from main()'s arguments */
void web_mark_fs_dirty(void);
uint32_t web_ticks(void);
void web_sleep_ms(uint32_t ms);

/* Control block words are shared with JS, which uses Atomics on them. */
static inline int32_t ctl_load(int index)
{
	return __atomic_load_n(&web_ctl()[index], __ATOMIC_SEQ_CST);
}

static inline void ctl_store(int index, int32_t value)
{
	__atomic_store_n(&web_ctl()[index], value, __ATOMIC_SEQ_CST);
}

#endif /* NFS2SE_PLATFORM_H */
